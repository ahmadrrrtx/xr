/**
 * XR Cloud — database client.
 *
 * One schema, two drivers:
 *
 *   - `postgres` (postgres-js) — production. The deployment target named in the
 *     phase brief.
 *   - `pglite` — an in-process WASM Postgres. This exists so that `bun test` and
 *     `bun run dev` work with **zero infrastructure**, which is what lets this
 *     phase's acceptance tests actually be executed rather than merely written.
 *     `loadEnv` refuses `pglite` in production, so it can never silently become
 *     the production database.
 *
 * Both drivers speak the same `pg-core` schema, so a migration generated by
 * drizzle-kit applies to either and the SQL is identical.
 *
 * Art. III.2 — one source of truth per concern: there is exactly one place that
 * opens a connection, and it is this file.
 */

import { PGlite } from "@electric-sql/pglite";
import { drizzle as drizzlePglite, type PgliteDatabase } from "drizzle-orm/pglite";
import { drizzle as drizzlePostgres, type PostgresJsDatabase } from "drizzle-orm/postgres-js";
import postgres from "postgres";

import { loadEnv } from "../env.ts";
import * as schema from "./schema.ts";

/**
 * Both drivers produce a Drizzle query builder over the same `pg-core` schema.
 * Declaring this as a *union* would intersect the two builder signatures and make
 * calls like `.onConflictDoNothing({ target })` resolve against the wrong
 * overload — a type-level failure with no runtime meaning. So the canonical type
 * is the Postgres one and the PGlite handle is cast once, here, with the reason
 * recorded. It is a genuine widening: `PgliteDatabase` implements the same
 * `PgDatabase` query-building surface.
 */
export type CloudDb = PostgresJsDatabase<typeof schema>;

/** Narrow the PGlite handle to the canonical type, once. */
function asCloudDb(db: PgliteDatabase<typeof schema>): CloudDb {
  return db as unknown as CloudDb;
}

/**
 * A handle that also exposes the query-building surface. Route code only ever
 * needs the query builder, so `CloudDb` is what it sees; `DatabaseHandle` adds
 * lifecycle for the two callers that must manage it (boot and tests).
 */
export interface MigrationReport {
  readonly applied: readonly string[];
  readonly skipped: readonly string[];
  readonly durationMs: number;
}

export interface DatabaseHandle {
  readonly db: CloudDb;
  readonly driver: "postgres" | "pglite";
  /**
   * Apply `drizzle/*.sql` migrations that are not already in the journal.
   *
   * Idempotency is tracked in a journal table, NOT by swallowing "already exists"
   * errors. The difference matters: swallowing an error also swallows a genuinely
   * failed `ALTER TABLE`, which is how a database ends up half-migrated with a
   * green deploy log.
   */
  migrate(): Promise<MigrationReport>;
  /** Names of migrations already applied, in apply order. */
  appliedMigrations(): Promise<readonly string[]>;
  /** Cheap liveness probe — one statement, no table access. */
  ping(): Promise<boolean>;
  close(): Promise<void>;
}

/**
 * Statement-level split.
 *
 * drizzle-kit separates statements with a line that is exactly
 * `--> statement-breakpoint`. Splitting on that marker (rather than on `;`) is
 * the only correct way to do this: a migration can legitimately contain a
 * semicolon inside a function body or a string literal, and a naive `;` split
 * turns one valid statement into two broken ones.
 */
function splitStatements(sql: string): string[] {
  return sql
    .split(/^\s*-->\s*statement-breakpoint\s*$/m)
    .map((chunk) => chunk.trim())
    .filter((chunk) => chunk.length > 0 && !/^--\s/.test(chunk.split("\n")[0] ?? ""));
}

/**
 * The migration journal. One row per applied file.
 *
 * Named with the `xr_` prefix because this service may share a database with other
 * things during development, and a bare `migrations` table is exactly the kind of
 * name two tools both want.
 */
const JOURNAL_TABLE = "xr_cloud_migrations";

async function ensureJournal(run: (statement: string) => Promise<unknown>): Promise<void> {
  await run(
    `create table if not exists ${JOURNAL_TABLE} (\n` +
      `  name text primary key,\n` +
      `  applied_at timestamptz not null default now(),\n` +
      `  duration_ms integer not null default 0\n` +
      `)`,
  );
}

/**
 * Read the journal without caring which driver answered.
 *
 * The two drivers disagree about the shape of a raw query result, and getting this
 * wrong is silent rather than loud: postgres-js returns `{ rows: [...] }`, while
 * PGlite's `exec()` returns an *array of* `{ rows: [...] }` — one entry per
 * statement in the call. Treating the outer array as the row list yields
 * `[undefined]`, which looks like "one migration applied" and leaves every
 * migration permanently pending. Normalising here is cheaper than remembering.
 */
async function readJournal(run: (statement: string) => Promise<unknown>): Promise<string[]> {
  const raw = await run(`select name from ${JOURNAL_TABLE} order by applied_at asc, name asc`);

  const candidates: unknown[] = [];
  const first = Array.isArray(raw) ? raw[0] : raw;
  if (Array.isArray(raw)) {
    // Either `[{ name }]` (flat rows) or `[{ rows: [{ name }] }]` (PGlite).
    const inner = (first as { rows?: unknown } | undefined)?.rows;
    if (Array.isArray(inner)) candidates.push(...inner);
    else candidates.push(...raw);
  } else if (raw && typeof raw === "object" && Array.isArray((raw as { rows?: unknown }).rows)) {
    candidates.push(...((raw as { rows: unknown[] }).rows));
  }

  return candidates
    .map((row) => (row as { name?: unknown } | null)?.name)
    .filter((name): name is string => typeof name === "string");
}

interface MigrationRunner {
  /** Execute one statement. */
  run(statement: string): Promise<unknown>;
  /** Log a human-readable line. */
  log(line: string): void;
}

async function loadMigrationFiles(): Promise<Array<{ name: string; body: string }>> {
  const dir = new URL("../../drizzle/", import.meta.url);
  let entries: string[];
  try {
    entries = Array.from(await Array.fromAsync(new Bun.Glob("*.sql").scan({ cwd: dir.pathname }))).sort();
  } catch {
    return [];
  }
  const out: Array<{ name: string; body: string }> = [];
  for (const name of entries) {
    out.push({ name, body: await Bun.file(new URL(name, dir)).text() });
  }
  return out;
}

async function applyMigrations(runner: MigrationRunner): Promise<MigrationReport> {
  const startedAt = Date.now();
  await ensureJournal(runner.run);
  const alreadyApplied = new Set(await readJournal(runner.run));

  const files = await loadMigrationFiles();
  if (files.length === 0) {
    runner.log("drizzle/ has no .sql files — nothing to apply");
    return { applied: [], skipped: [], durationMs: Date.now() - startedAt };
  }

  const applied: string[] = [];
  const skipped: string[] = [];

  for (const file of files) {
    if (alreadyApplied.has(file.name)) {
      skipped.push(file.name);
      continue;
    }
    const statements = splitStatements(file.body);
    const fileStartedAt = Date.now();

    // One transaction per file. Postgres DDL is transactional, so a migration that
    // fails halfway leaves the schema exactly as it was — which means a failed
    // deploy does not need hand-written repairs before the retry.
    await runner.run("begin");
    try {
      for (const statement of statements) {
        await runner.run(statement);
      }
      const durationMs = Date.now() - fileStartedAt;
      await runner.run(
        `insert into ${JOURNAL_TABLE} (name, duration_ms) values ('${file.name.replace(/'/g, "''")}', ${durationMs})`,
      );
      await runner.run("commit");
      applied.push(file.name);
      runner.log(`applied ${file.name} (${statements.length} statements, ${durationMs} ms)`);
    } catch (error) {
      // Roll back, then rethrow with the offending statement quoted. A migration
      // failure that does not name the statement it died on is unactionable.
      try {
        await runner.run("rollback");
      } catch {
        // The connection may already be broken; the original error is the useful one.
      }
      const detail = error instanceof Error ? error.message : String(error);
      throw new Error(`migration ${file.name} failed and was rolled back: ${detail}`);
    }
  }

  return { applied, skipped, durationMs: Date.now() - startedAt };
}

export async function createDatabase(
  log: (line: string) => void = () => {},
): Promise<DatabaseHandle> {
  const env = loadEnv();

  if (env.DATABASE_DRIVER === "pglite") {
    const client = new PGlite(env.PGLITE_DIR);
    const db = asCloudDb(drizzlePglite(client, { schema }));
    await client.waitReady;
    const runPglite = async (statement: string): Promise<unknown> => client.exec(statement);
    // Boot applies migrations so a fresh clone with PGlite just works; in
    // production the `migrate` service runs first and this is a no-op.
    const bootReport = await applyMigrations({ run: runPglite, log });
    if (bootReport.applied.length > 0) log(`boot applied ${bootReport.applied.length} migration(s)`);
    return {
      db,
      driver: "pglite",
      migrate: async () => applyMigrations({ run: runPglite, log }),
      appliedMigrations: async () => readJournal(runPglite),
      ping: async () => {
        try {
          await client.query("select 1");
          return true;
        } catch {
          return false;
        }
      },
      close: async () => {
        await client.close();
      },
    };
  }

  if (!env.DATABASE_URL) {
    // Unreachable: loadEnv already refused this combination.
    throw new Error("DATABASE_URL missing for postgres driver");
  }

  const sql = postgres(env.DATABASE_URL, {
    // Bounded pool (Constitution Art. XII · Rule 3 — resources have ceilings).
    max: 10,
    idle_timeout: 20,
    connect_timeout: 10,
    // Never let a driver error reach a log line with the DSN in it.
    onnotice: () => {},
  });
  const db = drizzlePostgres(sql, { schema });
  const runPostgres = async (statement: string): Promise<unknown> => sql.unsafe(statement) as Promise<unknown>;
  await applyMigrations({ run: runPostgres, log });

  return {
    db,
    driver: "postgres",
    migrate: async () => applyMigrations({ run: runPostgres, log }),
    appliedMigrations: async () => readJournal(runPostgres),
    ping: async () => {
      try {
        await sql`select 1`;
        return true;
      } catch {
        return false;
      }
    },
    close: async () => {
      await sql.end({ timeout: 5 });
    },
  };
}
