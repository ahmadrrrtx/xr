/**
 * `/security` — the trust page.
 *
 * The brief asks for this page to be honest above all else, and the temptation
 * with a trust page is to be reassuring rather than accurate. Three rules govern
 * everything below:
 *
 *   1. **Every claim is checkable.** If something is encrypted, say with what. If
 *      a control is missing, name it in the "not done" column instead of omitting
 *      the row. A controls checklist with no gaps is not a checklist.
 *   2. **Nothing is described as certified that is not certified.** SOC 2 Type I is
 *      a roadmap item with a date we control. Type II is out of scope for v1.0.0
 *      and saying so is cheaper than a discovery call that ends badly.
 *   3. **The strongest claims are the ones we can make about not collecting
 *      things.** "We do not have it" beats "we protect it", every time.
 */

